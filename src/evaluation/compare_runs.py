"""
Build results/summary.md: one table row per evaluation run, oldest first.

Usage (from the project root):
    python -m src.evaluation.compare_runs
"""

from src.evaluation.runs import RESULTS_DIR, load_runs

def _num(key, digits=3):
    return lambda r: (f"{r['metrics'][key]:.{digits}f}" if key in r["metrics"] else "n/a")


def _with_ci(key):
    def fmt(r):
        m = r["metrics"]
        if key not in m:
            return "n/a"
        ci = m.get(f"{key}_ci95")
        return f"{m[key]:.3f} ({ci[0]:.2f}-{ci[1]:.2f})" if ci else f"{m[key]:.3f}"
    return fmt


COLUMNS = [
    ("Run", lambda r: r["name"]),
    ("Date", lambda r: r["run_id"][:10]),
    ("Questions", lambda r: f"{r['metrics']['n_answerable']}+{r['metrics'].get('n_unanswerable', 0)}"),
    ("Embedding model", lambda r: r["config"].get("EMBEDDING_MODEL", "?")),
    ("Hit@1", _num("hit@1")),
    ("Hit@5 (95% CI)", _with_ci("hit@5")),
    ("Strict hit@5", _num("strict_hit@5")),
    ("MRR@10", _num("mrr@10")),
    ("nDCG@10 (95% CI)", _with_ci("ndcg@10")),
    ("Abstain (unans.)", _num("abstain_rate_unanswerable")),
    ("False reject", _num("false_reject_rate")),
    ("p95 ms", lambda r: f"{r['metrics']['latency_ms_p95']:.0f}"),
    ("Commit", lambda r: (r["git"]["commit"] or "?") + ("*" if r["git"]["dirty"] else "")),
]


def build_table(runs):
    lines = ["| " + " | ".join(name for name, _ in COLUMNS) + " |",
             "|" + "---|" * len(COLUMNS)]
    for r in runs:
        lines.append("| " + " | ".join(fn(r) for _, fn in COLUMNS) + " |")
    return "\n".join(lines)


def main():
    runs = [r for r in load_runs() if r.get("kind") == "retrieval"]
    if not runs:
        print("No retrieval runs yet. Run: python -m src.evaluation.run_retrieval_eval --name <name>")
        return
    table = build_table(runs)
    text = (
        "# Evaluation results\n\n"
        "Generated by `python -m src.evaluation.compare_runs`. Each row links to "
        "`results/runs/<run_id>/run.json` with full settings and per-question results.\n"
        "`*` after a commit means the run had uncommitted code changes. Questions = answerable + unanswerable.\n"
        "95% CI = bootstrap confidence interval over questions: overlapping intervals mean a difference may be noise.\n\n"
        "## Retrieval\n\n" + table + "\n"
    )
    out = RESULTS_DIR / "summary.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(table)
    print(f"\nWritten to {out.relative_to(RESULTS_DIR.parent)}")


if __name__ == "__main__":
    main()
